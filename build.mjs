// Generates the deployable assets from the single source of truth in ../live:
//   public/index.html          the bundled prototype, patched exactly like live/server.js does it at startup
//   src/generated/bank.js      the question bank (taken from the bundle)
//   src/generated/scoring.js   the scoring module (taken from the bundle)
// Workers cannot read files or eval code at runtime, so all of this happens here, at build time.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const live = path.join(root, '..', 'live');
const SOURCE = fs.readFileSync(path.join(live, 'source.html'), 'utf8');
const serverSrc = fs.readFileSync(path.join(live, 'server.js'), 'utf8');

function bundleAsset(uuid) {
  const tag = '<script type="__bundler/manifest">';
  const i = SOURCE.lastIndexOf(tag);
  const manifest = JSON.parse(SOURCE.slice(i + tag.length, SOURCE.indexOf('</script>', i)));
  const e = manifest[uuid];
  const raw = Buffer.from(e.data, 'base64');
  return (e.compressed ? zlib.gunzipSync(raw) : raw).toString('utf8');
}

// buildPage() is reused verbatim from live/server.js so the two versions can never drift apart.
const start = serverSrc.indexOf('function buildPage() {');
const end = serverSrc.indexOf('\n}\n', start) + 2;
if (start < 0 || end < start) throw new Error('buildPage() not found in live/server.js');
const DEFAULT_PW = /const DEFAULT_PW = '([^']+)'/.exec(serverSrc)[1];
const html = new Function('SOURCE', 'DEFAULT_PW', serverSrc.slice(start, end) + '\nreturn buildPage();')(SOURCE, DEFAULT_PW);

const bank = JSON.parse(bundleAsset('e2df9d42-6527-44d8-ade3-e860f0aea4c6'));
const scoring = bundleAsset('435712ec-76cb-45de-b1f1-56cd1a06843f');

fs.mkdirSync(path.join(root, 'public'), { recursive: true });
fs.mkdirSync(path.join(root, 'src', 'generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'public', 'index.html'), html);
fs.writeFileSync(path.join(root, 'src', 'generated', 'bank.js'), '// generated by scripts/build.mjs — do not edit\nexport default ' + JSON.stringify(bank) + ';\n');
fs.writeFileSync(path.join(root, 'src', 'generated', 'scoring.js'), '// generated by scripts/build.mjs — do not edit\n' + scoring);
fs.writeFileSync(path.join(root, 'src', 'generated', 'config.js'), `// generated by scripts/build.mjs — do not edit\nexport const DEFAULT_PW = ${JSON.stringify(DEFAULT_PW)};\n`);
console.log('built: index.html', html.length, 'bytes; questions', bank.questions.length, '; default password for new users:', DEFAULT_PW);
